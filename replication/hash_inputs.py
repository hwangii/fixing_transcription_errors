"""Write a SHA-256 manifest of every frozen input machine A's analysis reads.

    python replication/hash_inputs.py            # all inputs (about 150 GB; tens of minutes)
    python replication/hash_inputs.py --check    # recompute and compare with the manifest

The input list is the one run_machineA.do preflights, rebuilt from the same
sources: the state names in config.do ($REP_A_STATES) and the model-output
state codes in run_machineA.do. If either file changes shape, this script
stops rather than hashing a different list.

Output: replication/input_manifest.md (tracked). A changed hash means a frozen
input changed since the manifest was written, and every number downstream of
it should be treated as unverified until rerun.
"""

import hashlib
import os
import re
import socket
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MANIFEST = REPO / "replication" / "input_manifest.md"

# Machine A's roots, as in config.do's ARTS-ECON-CM block.
SNU = "D:/SNU ECON Dropbox/sam hwang"
F = "F:"


def input_list():
    config = (REPO / "replication" / "config.do").read_text(encoding="utf-8")
    m = re.search(r'^global REP_A_STATES "([^"]+)"', config, re.M)
    if not m:
        sys.exit("config.do: REP_A_STATES not found")
    states = m.group(1).split()

    master = (REPO / "replication" / "run_machineA.do").read_text(encoding="utf-8")
    m = re.search(r"^foreach s in ([a-z ]+) \{\s*\n\s*local inputs .*merged_data\.dta", master, re.M)
    if not m:
        sys.exit("run_machineA.do: model-output state list not found")
    codes = m.group(1).split()

    snu_ft = f"{SNU}/fixing_transcription_errors/DATA"
    snu_ed = f"{SNU}/enum_date/DATA"
    f_ft = f"{F}/fixing_transcription_errors/DATA"
    f_ed = f"{F}/enum_date/DATA"
    model = f"{snu_ft}/TRANSCRIPTIONS/USCensus1940FullCount/output_and_output1_ssha2025"

    files = [
        f"{snu_ft}/ORIGINAL/census1940_all_labeled_data.dta",
        f"{snu_ed}/INTERMEDIATE/link1930_1940_ans_cleaned_noraceblock0.dta",
        f"{snu_ed}/INTERMEDIATE/link1930_1940_true_cleaned_noraceblock0.dta",
        f"{f_ed}/ORIGINAL/all_states_socio_demo_char_for_SSHA2025.dta",
    ]
    files += [f"{f_ft}/INTERMEDIATE/merged_{s}1940.dta" for s in states]
    files += [f"{model}/{c}/merged_data.dta" for c in codes]
    # Written by create_figures_SSHA2025.do; hashed so a -SkipRebuild run can
    # be tied to the analysis file it used.
    files.append(f"{snu_ed}/INTERMEDIATE/temp.dta")
    if len(states) != 50 or len(codes) != 49:
        sys.exit(f"expected 50 state files and 49 model folders, found {len(states)} and {len(codes)}")
    return files


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 23), b""):
            h.update(chunk)
    return h.hexdigest()


def short(path):
    return path.replace(SNU, "$REP_SNU").replace(F + "/", "$REP_F/")


def read_manifest():
    rows = {}
    for line in MANIFEST.read_text(encoding="utf-8").splitlines():
        m = re.match(r"\| `([^`]+)` \| [\d,]+ \| [\d-]+ \| `([0-9a-f]{64})` \|", line)
        if m:
            rows[m.group(1)] = m.group(2)
    return rows


def main():
    if socket.gethostname().upper() != "ARTS-ECON-CM":
        sys.exit("this manifest describes machine A's inputs; run it on ARTS-ECON-CM")
    check = "--check" in sys.argv[1:]
    files = input_list()
    missing = [f for f in files if not os.path.exists(f)]
    if missing:
        sys.exit("missing inputs:\n  " + "\n  ".join(missing))
    old = read_manifest() if check else {}

    rows, changed, t0 = [], [], time.time()
    total = sum(os.path.getsize(f) for f in files)
    done = 0
    for i, f in enumerate(files, 1):
        size = os.path.getsize(f)
        digest = sha256(f)
        done += size
        mtime = time.strftime("%Y-%m-%d", time.localtime(os.path.getmtime(f)))
        rows.append(f"| `{short(f)}` | {size:,} | {mtime} | `{digest}` |")
        if check and old.get(short(f)) != digest:
            changed.append(short(f))
        print(f"[{i}/{len(files)}] {done / total:6.1%}  {short(f)}", flush=True)

    if check:
        print(f"\n{len(files) - len(changed)} unchanged, {len(changed)} changed or new")
        for c in changed:
            print("  CHANGED:", c)
        sys.exit(1 if changed else 0)

    header = [
        "# Input manifest (machine A)",
        "",
        "Generated by `replication/hash_inputs.py`; do not edit by hand.",
        f"Written {time.strftime('%Y-%m-%d %H:%M')} on {socket.gethostname()}, "
        f"{len(files)} files, {total / 1e9:,.1f} GB, {(time.time() - t0) / 60:.0f} min.",
        "Paths use `config.do`'s roots. Check with `python replication/hash_inputs.py --check`.",
        "",
        "| File | Bytes | Modified | SHA-256 |",
        "|---|---|---|---|",
    ]
    MANIFEST.write_text("\n".join(header + rows) + "\n", encoding="utf-8")
    print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
